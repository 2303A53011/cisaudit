               color: var(--text-dim); min-width: 60px; }
    .ctrl-level { background: var(--bg3); border: 1px solid var(--border);
                  border-radius: 4px; padding: 1px 6px; font-size: 11px;
                  color: var(--purple); min-width: 24px; text-align: center; }
    .ctrl-title { flex: 1; }
    .badge {
      padding: 2px 10px; border-radius: 20px; font-size: 11px; font-weight: 700;
      text-transform: uppercase; letter-spacing: 0.06em; min-width: 46px;
      text-align: center;
    }
    .badge-PASS { background: #1a3a20; color: var(--green); border: 1px solid #2a5030; }
    .badge-FAIL { background: #3a1a1a; color: var(--red);   border: 1px solid #5a2020; }
    .badge-WARN { background: #3a2e00; color: var(--yellow); border: 1px solid #5a4a00; }
    .badge-SKIP { background: var(--bg3); color: var(--text-dim); border: 1px solid var(--border); }
