  for section in "${SECTIONS[@]}"; do
    local total="${SECTION_TOTAL[$section]:-0}"
    (( total > 0 )) || continue
    local score="${SECTION_SCORE[$section]:-0.0}"
    local sp="${SECTION_PASS[$section]:-0}"
    local sf="${SECTION_FAIL[$section]:-0}"
    local sw="${SECTION_WARN[$section]:-0}"
    local sk="${SECTION_SKIP[$section]:-0}"
    local name
    name="$(html_escape "${SECTION_NAMES[$section]:-$section}")"
    local cls
    cls="$(score_class "$score")"
    local fill_cls
    case "$cls" in
      score-good) fill_cls="fill-good" ;;
      score-warn) fill_cls="fill-warn" ;;
      *)          fill_cls="fill-bad"  ;;
    esac

    cat <<ROWEOF
      <tr>
        <td>$name</td>
        <td class="$cls" style="font-weight:600">${score}%</td>
        <td style="color:var(--green)">$sp</td>
        <td style="color:var(--red)">$sf</td>
        <td style="color:var(--yellow)">$sw</td>
        <td style="color:var(--text-dim)">$sk</td>
        <td>
          <div class="section-progress">
            <div class="progress-bar">
              <div class="progress-fill $fill_cls" style="width:${score}%"></div>
            </div>
          </div>
        </td>
      </tr>
ROWEOF
  done

  cat <<HTMLEOF2
    </tbody>
  </table>

  <!-- Control Detail -->
  <h2>Control Results</h2>
HTMLEOF2

  local current_section=""
  for id in "${RESULT_ORDER[@]}"; do
    local section="${CTRL_SECTION[$id]}"
    local status="${RESULT_STATUS[$id]:-SKIP}"
    local title
    title="$(html_escape "${CTRL_TITLE[$id]}")"
    local level="${CTRL_LEVEL[$id]:-1}"
    local desc
    desc="$(html_escape "${CTRL_DESCRIPTION[$id]}")"
    local evidence
    evidence="$(html_escape "${RESULT_EVIDENCE[$id]}")"
    local fix
    fix="$(html_escape "${CTRL_REMEDIATION[$id]}")"

    if [[ "$section" != "$current_section" ]]; then
      # Close previous section
      [[ -n "$current_section" ]] && echo "</div>"
      current_section="$section"
      local sname
      sname="$(html_escape "${SECTION_NAMES[$section]:-$section}")"
      local st="${SECTION_TOTAL[$section]:-0}"
      echo "<div class=\"controls-section\">"
      echo "<div class=\"section-header\">📂 $sname <span class=\"section-count\">$st controls</span></div>"
    fi

    # Auto-open FAIL controls; collapse PASS
    local open_attr=""
    [[ "$status" == "FAIL" || "$status" == "WARN" ]] && open_attr=" open"

    echo "<details${open_attr}>"
    echo "  <summary>"
    echo "    <span class=\"ctrl-id\">$id</span>"
    echo "    <span class=\"ctrl-level\">L${level}</span>"
    echo "    <span class=\"ctrl-title\">$title</span>"
    echo "    <span class=\"badge badge-${status}\">${status}</span>"
    echo "  </summary>"
    echo "  <div class=\"ctrl-detail\">"
    if [[ -n "$desc" ]]; then
      echo "    <div class=\"detail-row\"><div class=\"detail-label\">Description</div>"
      echo "    <div class=\"detail-value\">$desc</div></div>"
    fi
    if [[ -n "$evidence" ]]; then
      echo "    <div class=\"detail-row\"><div class=\"detail-label\">Evidence</div>"
      echo "    <div class=\"detail-value\">$evidence</div></div>"
    fi
    if [[ -n "$fix" && ( "$status" == "FAIL" || "$status" == "WARN" ) ]]; then
      echo "    <div class=\"detail-row\"><div class=\"detail-label\">Remediation</div>"
      echo "    <div class=\"detail-value remediation\">$fix</div></div>"
    fi
    echo "  </div>"
    echo "</details>"
  done

  [[ -n "$current_section" ]] && echo "</div>"

  cat <<FOOTEREOF

</main>

<footer>
  <p>cisaudit v${CISAUDIT_VERSION} &nbsp;|&nbsp; $(html_escape "$BENCHMARK_ID") &nbsp;|&nbsp;
     Generated $timestamp on $(html_escape "$host")</p>
  <p style="margin-top:8px">
    ⚠️ Passing all controls does not mean the system is unbreakable.
    CIS hardening reduces attack surface and blast radius; defense-in-depth is still required.
  </p>
</footer>

</body>
</html>
FOOTEREOF
}
