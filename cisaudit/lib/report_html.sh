      details { border: 1px solid #ccc; }
      details[open] { page-break-inside: avoid; }
    }
  </style>
</head>
<body>

<header>
  <div class="logo"><span class="logo-icon">🔒</span> Linux CIS Hardening Auditor</div>
  <div class="subtitle">$(html_escape "$BENCHMARK_ID")</div>
  <div class="meta-row">
    <div class="meta-item"><strong>Host:</strong> $(html_escape "$host")</div>
    <div class="meta-item"><strong>Mode:</strong> $(html_escape "$mode")</div>
    <div class="meta-item"><strong>Generated:</strong> $timestamp</div>
    <div class="meta-item"><strong>Version:</strong> cisaudit v$(html_escape "$CISAUDIT_VERSION")</div>
  </div>
</header>

