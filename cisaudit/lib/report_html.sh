#!/usr/bin/env bash
# lib/report_html.sh — Standalone dark-themed HTML report
# Part of cisaudit — Linux CIS Hardening Auditor
#
# Generates a single self-contained HTML file with:
#   - Embedded CSS (dark theme + print stylesheet)
#   - <details>-based collapsible control list
#   - No external dependencies (no CDN, no fonts from internet)

# ── HTML entity escaping ──────────────────────────────────────────────────────
html_escape() {
  local s="$1"
  s="${s//&/&amp;}"
  s="${s//</&lt;}"
  s="${s//>/&gt;}"
  s="${s//\"/&quot;}"
  echo -n "$s"
}

# ── Score color class ─────────────────────────────────────────────────────────
score_class() {
  local score="$1"
  if awk -v s="$score" 'BEGIN { exit !(s >= 80) }'; then
    echo "score-good"
  elif awk -v s="$score" 'BEGIN { exit !(s >= 50) }'; then
    echo "score-warn"
  else
    echo "score-bad"
  fi
}

# ── Main entry point ──────────────────────────────────────────────────────────
emit_html_report() {
  local timestamp
  timestamp="$(date '+%Y-%m-%d %H:%M:%S')"
  local host
  host="$(hostname 2>/dev/null || echo unknown)"
  local mode
  [[ "$SYSROOT" == "/" ]] && mode="Live System" || mode="Test Mode (${SYSROOT})"

