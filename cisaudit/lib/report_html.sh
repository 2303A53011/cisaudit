            display: flex; align-items: center; gap: 12px; margin-bottom: 8px; }
    .logo-icon { font-size: 36px; }
    .subtitle { color: var(--text-dim); font-size: 13px; }
    .meta-row { display: flex; gap: 24px; margin-top: 16px; flex-wrap: wrap; }
    .meta-item { background: var(--bg3); border: 1px solid var(--border);
                 border-radius: 6px; padding: 6px 14px; font-size: 12px;
                 color: var(--text-dim); }
    .meta-item strong { color: var(--text); }

    /* ── Main layout ── */
    main { max-width: 1100px; margin: 32px auto; padding: 0 40px; }

    /* ── Score card ── */
    .score-card {
      background: var(--bg2); border: 1px solid var(--border); border-radius: 12px;
      padding: 28px 32px; display: flex; align-items: center; gap: 40px;
      margin-bottom: 32px; flex-wrap: wrap;
    }
    .big-score { font-size: 64px; font-weight: 800; line-height: 1; }
    .score-good { color: var(--green); }
    .score-warn { color: var(--yellow); }
    .score-bad  { color: var(--red); }
    .score-label { color: var(--text-dim); font-size: 13px; margin-top: 4px; }
    .counters { display: flex; gap: 24px; flex-wrap: wrap; }
    .counter { text-align: center; }
    .counter .val { font-size: 32px; font-weight: 700; line-height: 1; }
    .counter .lbl { font-size: 11px; text-transform: uppercase;
                    letter-spacing: 0.08em; color: var(--text-dim); margin-top: 2px; }
    .pass-val  { color: var(--green); }
    .fail-val  { color: var(--red); }
    .warn-val  { color: var(--yellow); }
    .skip-val  { color: var(--text-dim); }

    /* ── Progress bar ── */
    .progress-bar { background: var(--bg3); border-radius: 4px; height: 8px;
                    overflow: hidden; flex: 1; min-width: 80px; }
    .progress-fill { height: 100%; border-radius: 4px; transition: width 0.3s; }
    .fill-good { background: linear-gradient(90deg, #238636, #3fb950); }
    .fill-warn { background: linear-gradient(90deg, #9e6a03, #d29922); }
    .fill-bad  { background: linear-gradient(90deg, #b91c1c, #f85149); }

    /* ── Section table ── */
    h2 { color: var(--text); font-size: 16px; font-weight: 600;
         margin: 32px 0 16px; border-bottom: 1px solid var(--border); padding-bottom: 8px; }
    table { width: 100%; border-collapse: collapse; margin-bottom: 32px; }
    th { text-align: left; color: var(--text-dim); font-weight: 500; font-size: 12px;
         text-transform: uppercase; letter-spacing: 0.06em;
         padding: 8px 12px; border-bottom: 1px solid var(--border); }
    td { padding: 10px 12px; border-bottom: 1px solid var(--border); vertical-align: middle; }
    tr:last-child td { border-bottom: none; }
    tr:hover td { background: var(--bg3); }
    .section-progress { display: flex; align-items: center; gap: 10px; min-width: 140px; }
    .section-pct { font-weight: 600; min-width: 42px; }

